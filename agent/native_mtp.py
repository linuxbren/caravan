"""Experimental matching-checkpoint Qwen3.5 MTP (Day 17).

Architecture adapted from MIT-licensed mlx-vlm qwen3_5_mtp (Prince Canuma et al.).
Upstream copyright/permission notice: native_mtp.LICENSE.
Uses mlx-lm decoder primitives, not mlx-vlm as a runtime dependency.
Greedy-only, one draft token per verify; fresh request caches. Hybrid rejection
restores a full cache snapshot and replays the kept input. No unsafe GDN trim.
"""
from __future__ import annotations
import copy
import json
import time
from pathlib import Path


def head_path(model_dir):
    p = Path(model_dir) / "caravan-mtp"
    return p if (p / "model.safetensors").is_file() and (p / "config.json").is_file() else None


def validate_pair(target_config, head_config):
    text = target_config.get("text_config", target_config)
    wanted = head_config.get("text_config", {})
    if target_config.get("model_type") != "qwen3_5" or text.get("num_experts", 0):
        raise ValueError("native MTP currently supports dense Qwen3.5 only")
    if text.get("mtp_num_hidden_layers", 1) != 1 or not text.get("tie_word_embeddings", True):
        raise ValueError("native MTP needs one head layer and tied embeddings")
    for key in ("hidden_size", "vocab_size", "num_hidden_layers", "intermediate_size"):
        if text.get(key) != wanted.get(key):
            raise ValueError(f"MTP target mismatch: {key}")
    if head_config.get("target_repo") != "Orvena/Orvena-4B-MLX-4bit":
        raise ValueError("MTP head must name the exact supported target checkpoint")
    return text


def load_head(model_dir, target):
    import mlx.core as mx
    import mlx.nn as nn
    from dataclasses import replace
    from mlx_lm.models.qwen3_5 import TextModelArgs, DecoderLayer
    p = head_path(model_dir)
    if p is None:
        raise ValueError("native MTP weights missing: install matching caravan-mtp head first")
    cfg = json.loads((Path(model_dir) / "config.json").read_text())
    hc = json.loads((p / "config.json").read_text())
    text = validate_pair(cfg, hc)
    # The marker is generated by fetch_native_mtp for this exact target only.
    marker = json.loads((p / "config.json").read_text())
    if marker.get("target_config_sha256"):
        import hashlib
        actual = hashlib.sha256((Path(model_dir) / "config.json").read_bytes()).hexdigest()
        if actual != marker["target_config_sha256"]:
            raise ValueError("MTP target config changed since extraction")
    args = replace(TextModelArgs.from_dict(text), num_hidden_layers=1, full_attention_interval=1)

    class Head(nn.Module):
        def __init__(self):
            super().__init__()
            self.fc = nn.Linear(2 * args.hidden_size, args.hidden_size, bias=False)
            self.pre_fc_norm_embedding = nn.RMSNorm(args.hidden_size, eps=args.rms_norm_eps)
            self.pre_fc_norm_hidden = nn.RMSNorm(args.hidden_size, eps=args.rms_norm_eps)
            self.layers = [DecoderLayer(args, 0)]
            self.norm = nn.RMSNorm(args.hidden_size, eps=args.rms_norm_eps)

        def __call__(self, tokens, hidden, cache):
            from mlx_lm.models.base import create_attention_mask
            emb = target.model.embed_tokens(tokens)
            h = self.fc(mx.concatenate([self.pre_fc_norm_embedding(emb),
                                       self.pre_fc_norm_hidden(hidden)], axis=-1))
            mask = create_attention_mask(h, cache[0])
            h = self.layers[0](h, mask=mask, cache=cache[0])
            return target.model.embed_tokens.as_linear(self.norm(h))

    head = Head()
    weights = mx.load(str(p / "model.safetensors"))
    head.load_weights(list(weights.items()), strict=True)
    mx.eval(head.parameters())
    return head


def generate(target, head, prompt, max_tokens, *, enabled=True, cancel=None, stats=None):
    """Yield (id, from_head). Exact target argmax verification; no sampling claim.

    Target hidden states are post-final-norm, as in mlx-vlm's MTP interface.
    Every call owns caches, so rejected hybrid state never leaks into sessions.
    """
    import mlx.core as mx
    from mlx_lm.models.cache import KVCache
    stats = stats if stats is not None else {}
    stats.update(mode="native_mtp" if enabled else "baseline", proposed=0, accepted=0,
                 verify_rounds=0, replays=0, k=1, fresh_cache=True)
    cache = target.make_cache()
    dc = [KVCache()]
    lm = target.language_model

    def forward(ids):
        h = target.model(mx.array([ids], mx.uint32), cache=cache)
        logits = (target.model.embed_tokens.as_linear(h) if lm.args.tie_word_embeddings
                  else lm.lm_head(h))
        mx.eval(logits, h)
        return logits, h

    if max_tokens <= 0:
        return
    logits, hidden = forward(list(prompt))
    y = int(mx.argmax(logits[0, -1]).item())
    yield y, False
    n = 1
    if enabled and n < max_tokens:
        shifted = list(prompt[1:]) + [y]
        dl = head(mx.array([shifted], mx.uint32), hidden, dc)
        proposal = int(mx.argmax(dl[0, -1]).item())
    while n < max_tokens and not (cancel and cancel.is_set()):
        if not enabled or n + 1 >= max_tokens:
            logits, hidden = forward([y])
            y = int(mx.argmax(logits[0, -1]).item())
            n += 1
            yield y, False
            continue
        # KVCache + ArraysCache deepcopy is intentionally conservative. Never trim
        # a GatedDeltaNet recurrence as if it were ordinary attention KV.
        before = copy.deepcopy(cache)
        logits, hidden = forward([y, proposal])
        checked = int(mx.argmax(logits[0, 0]).item())
        stats["verify_rounds"] += 1
        stats["proposed"] += 1
        if checked == proposal:
            stats["accepted"] += 1
            n += 1
            yield proposal, True
            bonus = int(mx.argmax(logits[0, 1]).item())
            if n >= max_tokens:
                return
            n += 1
            yield bonus, False
            pairs = [proposal, bonus]
            pair_hidden = hidden
            y = bonus
        else:
            cache = before
            _, replay_hidden = forward([y])
            stats["replays"] += 1
            n += 1
            yield checked, False
            pairs = [checked]
            pair_hidden = replay_hidden
            y = checked
        if n < max_tokens:
            dl = head(mx.array([pairs], mx.uint32), pair_hidden, dc)
            proposal = int(mx.argmax(dl[0, -1]).item())
    stats["accepted_frac"] = stats["accepted"] / max(stats["proposed"], 1)
