#!/usr/bin/env python3
"""Renders launchd/com.caravan.llama-server.plist from the same command
builder the agent uses (supervisor.build_head_command), so the hand-
managed plist stops carrying hand-typed flags, a literal blob path, and a
literal RPC address that can silently go stale.

Writes to stdout unless --output is given. It never touches launchd or
~/Library/LaunchAgents -- write the file, review the diff, then
re-bootstrap yourself (see launchd/README.md).

    python3 agent/render_llama_plist.py                       # defaults, to stdout
    python3 agent/render_llama_plist.py --rpc auto            # derive node-b's address
    python3 agent/render_llama_plist.py --model qwen3:30b-a3b \\
        --ubatch-size 1024 --output launchd/com.caravan.llama-server.plist

--rpc: comma-separated host:port list, or "auto" to run the agent's peer
discovery (Tailscale + mDNS, upgraded to a Thunderbolt fast path when one
answers) -- that needs caravan-agent's health endpoint running on node-b.
Default: $CARAVAN_RPC_ADDR > "llama_server.rpc" in ~/.caravan/config.json
> 169.254.104.38:50052 (node-b's Thunderbolt-bridge link-local address;
link-local addresses are self-assigned and can change).

--model-path skips the Ollama lookup and uses a GGUF path as-is.
"""
import argparse
import plistlib
import socket
import sys
from pathlib import Path

import config
import ollama_store
import supervisor

LABEL = "com.caravan.llama-server"
LOG_PATH = Path.home() / "Library" / "Logs" / "caravan" / "llama-server.log"


def discover_rpc_addrs() -> list:
    import caravan_agent  # heavy (discovery modules) -- only for --rpc auto
    peers = caravan_agent.discover_peers(None, self_hostname=socket.gethostname())
    return caravan_agent._rpc_addrs_from_peers(peers)


def build_plist(cmd: list) -> dict:
    return {
        "Label": LABEL,
        "Comment": "Caravan: node-a llama-server, sharded across node-a (Metal) + node-b (RPC). "
                   "Generated by agent/render_llama_plist.py",
        "ProgramArguments": cmd,
        "WorkingDirectory": str(config.LLAMA_SERVER_BIN.parent.parent.parent),
        "RunAtLoad": True,
        "KeepAlive": True,
        "ThrottleInterval": 10,
        "ExitTimeOut": 20,
        "StandardInPath": "/dev/null",
        "StandardOutPath": str(LOG_PATH),
        "StandardErrorPath": str(LOG_PATH),
    }


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--model", default=None,
                        help="Ollama model (default: $CARAVAN_MODEL / config file / muse-glimmer)")
    parser.add_argument("--model-path", default=None, help="explicit GGUF path (skips Ollama lookup)")
    parser.add_argument("--rpc", default=None,
                        help="host:port[,host:port] or 'auto' (default: $CARAVAN_RPC_ADDR / "
                             "config llama_server.rpc / 169.254.104.38:50052)")
    parser.add_argument("--config", default=None, help="JSON config file")
    parser.add_argument("--output", "-o", default=None, help="write here instead of stdout")
    config.add_llama_cli_args(parser)
    args = parser.parse_args(argv)

    config_path = Path(args.config).expanduser() if args.config else None
    overrides = config.llama_overrides_from_args(args)
    overrides["rpc"] = args.rpc if args.rpc and args.rpc != "auto" else None
    try:
        settings = config.resolve_llama_settings(overrides, config_path)
    except ValueError as e:
        parser.error(str(e))

    if args.model_path:
        blob = Path(args.model_path).expanduser()
    else:
        model = config.resolve_target_model(args.model, config_path)
        blob = ollama_store.resolve_blob_path(model)
        if blob is None:
            print(f"error: model {model!r} not found in the Ollama store "
                  f"({ollama_store.MANIFESTS_ROOT}); pull it, or pass --model-path.",
                  file=sys.stderr)
            return 1

    if args.rpc == "auto":
        rpc_addrs = discover_rpc_addrs()
        if not rpc_addrs:
            print("error: --rpc auto found no live Caravan peers (is caravan-agent running "
                  "on node-b?). Pass --rpc host:port instead.", file=sys.stderr)
            return 1
        print(f"[render] discovered rpc: {','.join(rpc_addrs)}", file=sys.stderr)
    else:
        rpc_addrs = [a.strip() for a in settings.rpc.split(",") if a.strip()]

    cmd = supervisor.build_head_command(str(blob), rpc_addrs, settings)
    data = plistlib.dumps(build_plist(cmd), sort_keys=False)
    if args.output:
        Path(args.output).write_bytes(data)
        print(f"[render] wrote {args.output} -- re-bootstrap to apply (launchd/README.md)",
              file=sys.stderr)
    else:
        sys.stdout.write(data.decode("utf-8"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
